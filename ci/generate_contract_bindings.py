def generate_all_bindings() -> Dict[Path, str]:
    version = get_contract_version()
    enums = load_enums()
    schemas = load_schemas()
    inputs = collect_input_paths()

    bindings: Dict[Path, str] = {}

    # 1. Manifest
    bindings[GENERATED_DIR / "contract_version.json"] = generate_contract_version_manifest(version, inputs)

    # 2. C++
    bindings[GENERATED_DIR / "cpp/enums.hpp"] = generate_cpp_enums(enums)
    bindings[GENERATED_DIR / "cpp/models.hpp"] = generate_cpp_models()

    # 3. Python
    bindings[GENERATED_DIR / "python/__init__.py"] = generate_python_init()
    bindings[GENERATED_DIR / "python/enums.py"] = generate_python_enums(enums)
    bindings[GENERATED_DIR / "python/models.py"] = generate_python_models()

    # 4. Kotlin
    bindings[GENERATED_DIR / "kotlin/Enums.kt"] = generate_kotlin_enums(enums)
    bindings[GENERATED_DIR / "kotlin/Models.kt"] = generate_kotlin_models()

    return bindings


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Deterministic contract bindings generator for C++, Python, and Kotlin."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check on-disk generated bindings against expected output; exits with non-zero on drift.",
    )
    args = parser.parse_args()

    expected_bindings = generate_all_bindings()

    if args.check:
        drift_errors = []
        for path, expected_content in sorted(expected_bindings.items(), key=lambda x: str(x[0])):
            rel_path = path.relative_to(ROOT).as_posix()
            if not path.is_file():
                drift_errors.append(f"missing generated file: {rel_path}")
            else:
                actual_content = path.read_text(encoding="utf-8")
                if actual_content != expected_content:
                    drift_errors.append(f"drift in generated file: {rel_path}")

        if drift_errors:
            sys.stderr.write("Generated contract bindings drift detected:\n")
            for err in drift_errors:
                sys.stderr.write(f"  - {err}\n")
            sys.exit(1)

        print("PASS: generated contract bindings")
        return 0

    # Generation mode
    for path, content in expected_bindings.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")

    print(f"PASS: successfully generated {len(expected_bindings)} contract binding artifacts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
