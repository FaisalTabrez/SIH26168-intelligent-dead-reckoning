#!/usr/bin/env python3
"""
Authoritative deterministic contract bindings generator for SIH26168.
Implements WP-01.4 as specified by Architecture Revision 3 Component C-20
and contracts/INTERFACE_SCHEMA_PLAN.md.

Produces deterministic native data models in C++20, Python, and Kotlin
from JSON Schema Draft 2020-12 and canonical enum contract definitions.
Adheres strictly to docs/GENERATED_FILE_POLICY.md.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS_DIR = ROOT / "contracts"
ENUMS_DIR = CONTRACTS_DIR / "enums"
SCHEMAS_DIR = CONTRACTS_DIR / "schemas/common"
VERSION_FILE = CONTRACTS_DIR / "VERSION"
GENERATED_DIR = CONTRACTS_DIR / "generated"

GENERATOR_VERSION = "1.0.0-bootstrap"
COMMAND_TAG = "python ci/generate_contract_bindings.py"


def get_contract_version() -> str:
    if VERSION_FILE.is_file():
        return VERSION_FILE.read_text(encoding="utf-8").strip()
    return "1.0.0-bootstrap"


def make_header(sources: str, comment_prefix: str = "//") -> str:
    return (
        f"{comment_prefix} Auto-generated by ci/generate_contract_bindings.py. DO NOT EDIT.\n"
        f"{comment_prefix} Source schemas: {sources}\n"
        f"{comment_prefix} Generator version: {GENERATOR_VERSION}\n"
        f"{comment_prefix} Deterministic command: {COMMAND_TAG}\n\n"
    )


def load_enums() -> Dict[str, Dict]:
    enums = {}
    for p in sorted(ENUMS_DIR.glob("*.json")):
        data = json.loads(p.read_text(encoding="utf-8"))
        enums[p.name] = data
    return enums


def load_schemas() -> Dict[str, Dict]:
    schemas = {}
    for p in sorted(SCHEMAS_DIR.glob("*.json")):
        data = json.loads(p.read_text(encoding="utf-8"))
        schemas[p.name] = data
    return schemas


def collect_input_paths() -> List[str]:
    inputs = [VERSION_FILE.relative_to(ROOT).as_posix()]
    for p in sorted(ENUMS_DIR.glob("*.json")):
        inputs.append(p.relative_to(ROOT).as_posix())
    for p in sorted(SCHEMAS_DIR.glob("*.json")):
        inputs.append(p.relative_to(ROOT).as_posix())
    return sorted(inputs)


def generate_contract_version_manifest(version: str, inputs: List[str]) -> str:
    data = {
        "contract_version": version,
        "generated_from": inputs,
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def generate_cpp_enums(enums: Dict[str, Dict]) -> str:
    out = make_header("contracts/enums/*.json", "//")
    out += "#pragma once\n\n"
    out += "#include <cstdint>\n"
    out += "#include <optional>\n"
    out += "#include <string_view>\n\n"
    out += "namespace sih26168::contracts {\n\n"

    # Enums to generate
    enum_list: List[Tuple[str, List[str]]] = []
    for filename, data in sorted(enums.items()):
        name = data.get("enum_name")
        if name and "values" in data:
            enum_list.append((name, data["values"]))
        elif filename == "navigation_states_v1.json":
            if "provenance" in data:
                enum_list.append(("ProvenanceClassificationV1", data["provenance"]))

    # Also add ProvenanceTypeV1 from common provenance schema if not already present
    if not any(name == "ProvenanceTypeV1" for name, _ in enum_list):
        enum_list.append(("ProvenanceTypeV1", ["LIVE_DEVICE", "DETERMINISTIC_REPLAY", "LIVE", "REPLAY"]))

    for enum_name, values in sorted(enum_list, key=lambda x: x[0]):
        out += f"enum class {enum_name} : uint8_t {{\n"
        for v in values:
            out += f"    {v},\n"
        out += "};\n\n"

        # to_string
        out += f"[[nodiscard]] constexpr std::string_view to_string({enum_name} value) noexcept {{\n"
        out += "    switch (value) {\n"
        for v in values:
            out += f'        case {enum_name}::{v}: return "{v}";\n'
        out += '        default: return "UNKNOWN";\n'
        out += "    }\n"
        out += "}\n\n"

        # parse
        out += f"[[nodiscard]] constexpr std::optional<{enum_name}> parse_{enum_name}(std::string_view str) noexcept {{\n"
        for v in values:
            out += f'    if (str == "{v}") return {enum_name}::{v};\n'
        out += "    return std::nullopt;\n"
        out += "}\n\n"

    out += "} // namespace sih26168::contracts\n"
    return out


